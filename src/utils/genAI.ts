// Simulate AI response generation with different response times and content
export const generateAIResponse = async (prompt: string): Promise<string> => {
  // In a real implementation, this would call an AI service API
  console.log('AI prompt received:', prompt);
  
  // Simulate processing time
  await new Promise(resolve => setTimeout(resolve, 1500));
  
  // Simple pattern matching for demo purposes
  if (prompt.toLowerCase().includes('invest') || prompt.toLowerCase().includes('stock')) {
    return "When investing in stocks, consider your risk tolerance, investment timeline, and diversification strategy. A balanced portfolio typically includes a mix of stocks, bonds, and other assets based on your financial goals.";
  } else if (prompt.toLowerCase().includes('mutual fund') || prompt.toLowerCase().includes('fund')) {
    return "Mutual funds offer diversification and professional management. Look for funds with consistent performance, reasonable expense ratios, and investment strategies that align with your goals.";
  } else if (prompt.toLowerCase().includes('gold') || prompt.toLowerCase().includes('precious')) {
    return "Digital gold can serve as a hedge against inflation and market volatility. Consider allocating 5-10% of your portfolio to gold as part of your diversification strategy.";
  } else if (prompt.toLowerCase().includes('beginner') || prompt.toLowerCase().includes('start')) {
    return "For beginners, start with a emergency fund, then consider low-cost index funds. As you learn more, gradually expand into individual stocks or other investment vehicles that interest you.";
  } else if (prompt.toLowerCase().includes('risk') || prompt.toLowerCase().includes('safe')) {
    return "All investments carry some risk. Higher potential returns typically come with higher risk. Government bonds and treasury securities are generally considered lower risk, while individual stocks and cryptocurrencies tend to be higher risk.";
  } else {
    return "I'd be happy to help with your investment questions. You can ask about stocks, mutual funds, digital gold, investment strategies, or any other financial topics you're curious about.";
  }
};

